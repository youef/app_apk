"""Admin-only direct MP4 uploads for Al Ezz TV.

Files go straight from the browser to Supabase Storage using short-lived,
path-scoped signed TUS tokens. The service key is never sent to the browser.
The public download URL is stable (unlike temporary CDN stream signatures).
"""
from __future__ import annotations

import base64
import hashlib
import hmac
import json
import os
import time
import uuid
from datetime import datetime, timezone
from urllib.parse import parse_qs, quote, urlsplit

import requests
from fastapi import APIRouter, HTTPException, Request
from fastapi.responses import FileResponse
from pydantic import BaseModel, Field

from private_film_import import owner

router = APIRouter()
BUCKET = "aseel-video-uploads"
MAX_FILE_BYTES = 10 * 1024 * 1024 * 1024  # The project's Storage plan may be lower.
MAX_ROWS = 60


class StartUpload(BaseModel):
    filename: str = Field(min_length=5, max_length=220)
    title: str = Field(min_length=1, max_length=180)
    size_bytes: int = Field(gt=0, le=MAX_FILE_BYTES)


class FinishUpload(BaseModel):
    receipt: str = Field(min_length=30, max_length=4096)


def is_mp4(filename: str) -> bool:
    return (filename.lower().endswith(".mp4")
            and "/" not in filename and "\\" not in filename
            and "\x00" not in filename and len(filename) <= 220)


def _key() -> str:
    secret = os.getenv("ALEZZ_SUPABASE_SECRET_KEY") or os.getenv("ALEZZ_SUPABASE_SERVICE_ROLE_KEY")
    if not secret:
        raise HTTPException(503, "مفتاح Supabase الخاص بالخادم غير مضبوط في Render")
    return secret


def _receipt_secret() -> bytes:
    # Site secret is generated by Render; fallback is server-only Supabase secret.
    return (os.getenv("ALEZZ_SITE_SECRET") or _key()).encode("utf-8")


def _encode_receipt(payload: dict) -> str:
    data = base64.urlsafe_b64encode(
        json.dumps(payload, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
    ).decode("ascii").rstrip("=")
    signature = hmac.new(_receipt_secret(), data.encode("ascii"), hashlib.sha256).hexdigest()
    return data + "." + signature


def _decode_receipt(receipt: str, user_id: str) -> dict:
    try:
        data, provided = receipt.split(".", 1)
        correct = hmac.new(_receipt_secret(), data.encode("ascii"), hashlib.sha256).hexdigest()
        if not hmac.compare_digest(correct, provided):
            raise ValueError("bad signature")
        payload = json.loads(base64.urlsafe_b64decode(data + "=" * (-len(data) % 4)))
        if (payload.get("uid") != user_id or payload.get("exp", 0) < int(time.time())
                or not isinstance(payload.get("size"), int) or payload["size"] <= 0
                or not isinstance(payload.get("path"), str)
                or not payload["path"].startswith("uploads/")
                or not payload["path"].endswith(".mp4")):
            raise ValueError("expired or invalid")
        uuid.UUID(payload["path"].split("/")[-1][:-4])
        return payload
    except (ValueError, TypeError, KeyError, IndexError, json.JSONDecodeError) as exc:
        raise HTTPException(403, "انتهى تصريح الرفع أو أنه غير صالح؛ ابدأ رفعًا جديدًا") from exc


def _admin(request: Request, portal, *, mutation=False) -> str:
    if mutation:
        # Same-origin POST prevents CSRF against the HTTP-only admin cookie.
        if request.headers.get("origin", "") != str(request.base_url).rstrip("/"):
            raise HTTPException(403, "يجب تنفيذ الطلب من صفحة الاستديو نفسها")
    uid = str(owner(request, portal))
    try:
        if not portal.admin_active(uid):
            raise HTTPException(403, "حساب المسؤول غير نشط")
    except requests.RequestException as exc:
        raise HTTPException(503, "تعذّر التأكد من صلاحية المسؤول") from exc
    return uid


def _public_url(portal, path: str) -> str:
    return portal.db_url.rstrip("/") + "/storage/v1/object/public/" + BUCKET + "/" + quote(path, safe="/")


def _record(portal, path: str):
    rows = portal.upstream(
        "GET", "/rest/v1/aseel_uploaded_mp4", secret=True,
        params={"storage_path": "eq." + path,
                "select": "id,title,original_filename,storage_path,size_bytes,public_url,created_at",
                "limit": "1"},
    )
    return rows[0] if rows else None


def register(portal, template_path):
    @router.get("/studio/video-upload")
    def upload_page(request: Request):
        _admin(request, portal)
        return FileResponse(template_path, headers={"Cache-Control": "private, no-store"})

    @router.get("/api/studio/video-upload")
    def uploaded_files(request: Request):
        _admin(request, portal)
        _key()
        try:
            rows = portal.upstream("GET", "/rest/v1/aseel_uploaded_mp4", secret=True,
                params={"select": "id,title,original_filename,size_bytes,public_url,created_at",
                        "order": "created_at.desc", "limit": str(MAX_ROWS)})
        except (requests.RequestException, ValueError) as exc:
            raise HTTPException(503, "تعذّر قراءة ملفات الفيديو من Supabase") from exc
        return {"files": rows, "bucket": BUCKET}

    @router.post("/api/studio/video-upload/start")
    def start_upload(body: StartUpload, request: Request):
        user_id = _admin(request, portal, mutation=True)
        _key()
        if not is_mp4(body.filename):
            raise HTTPException(422, "يمكن رفع ملفات MP4 فقط")
        # A unique path prevents accidental overwrite or CDN cache collisions.
        path = "uploads/" + datetime.now(timezone.utc).strftime("%Y/%m/") + str(uuid.uuid4()) + ".mp4"
        try:
            signed = portal.upstream(
                "POST", "/storage/v1/object/upload/sign/" + BUCKET + "/" + path,
                secret=True, json={},
            )
            raw_url = signed.get("url", "")
            token = signed.get("token") or parse_qs(urlsplit(raw_url).query).get("token", [""])[0]
            if not token:
                raise ValueError("Supabase returned no signed upload token")
        except (requests.RequestException, ValueError) as exc:
            raise HTTPException(502, "تعذّر إصدار تصريح رفع إلى Supabase Storage") from exc
        payload = {"uid": user_id, "title": body.title.strip(),
                   "filename": body.filename, "size": body.size_bytes,
                   "path": path, "exp": int(time.time()) + 2 * 3600}
        host = portal.db_url.replace(".supabase.co", ".storage.supabase.co")
        return {"bucket": BUCKET, "path": path, "token": token,
                "tus_endpoint": host + "/storage/v1/upload/resumable",
                "public_key": portal.public_key,  # A publishable key, never a service key.
                "receipt": _encode_receipt(payload), "chunk_bytes": 6 * 1024 * 1024}

    @router.post("/api/studio/video-upload/finish")
    def finish_upload(body: FinishUpload, request: Request):
        user_id = _admin(request, portal, mutation=True)
        payload = _decode_receipt(body.receipt, user_id)
        path = payload["path"]
        try:
            info = portal.upstream(
                "GET", "/storage/v1/object/info/" + BUCKET + "/" + path,
                secret=True,
            )
        except requests.RequestException as exc:
            raise HTTPException(409, "لم يكتمل الملف في التخزين بعد؛ تحقق من نجاح الرفع") from exc
        meta = info.get("metadata") or {}
        try:
            real_size = int(meta.get("size") or info.get("size") or 0)
        except (ValueError, TypeError):
            real_size = 0
        mime = str(meta.get("mimetype") or info.get("mimetype") or "").split(";")[0].lower()
        if real_size <= 0 or real_size != payload["size"] or mime != "video/mp4":
            raise HTTPException(422, "فشل التحقق من حجم الفيديو أو صيغته MP4 داخل التخزين")
        try:
            existing = _record(portal, path)
            if existing:
                return {"file": existing, "saved": True}
            row = {"title": payload["title"], "original_filename": payload["filename"],
                   "storage_bucket": BUCKET, "storage_path": path,
                   "size_bytes": real_size, "uploaded_by": user_id,
                   "public_url": _public_url(portal, path)}
            saved = portal.upstream("POST", "/rest/v1/aseel_uploaded_mp4",
                                    secret=True, prefer="return=representation", json=row)
            if not saved:
                raise ValueError("The database did not return the saved video")
            return {"file": saved[0], "saved": True}
        except requests.RequestException as exc:
            # The MP4 is already safely stored. Do not delete a completed upload
            # because saving optional catalogue metadata temporarily failed.
            raise HTTPException(503, "الفيديو مرفوع، لكن فشل حفظ بياناته. أعد المحاولة دون إعادة الرفع") from exc
        except ValueError as exc:
            raise HTTPException(503, "تعذّر تأكيد حفظ الفيديو في الداتا") from exc
