"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const path=require("node:path");
const root=path.resolve(__dirname,"..");
const importer=fs.readFileSync(path.join(root,"admin/importer.js"),"utf8");
const html=fs.readFileSync(path.join(root,"admin/index.html"),"utf8");
const service=fs.readFileSync(path.join(root,"supabase/functions/aseel-inspect-media/index.ts"),"utf8");
new vm.Script(importer,{filename:"admin/importer.js"});
const ids=[...html.matchAll(/\bid="([^"]+)"/g)].map(x=>x[1]);
assert.equal(new Set(ids).size,ids.length,"Duplicate IDs in admin HTML");
const referenced=[...new Set([...importer.matchAll(/\$\("([A-Za-z0-9_-]+)"\)/g)].map(x=>x[1]))];
for(const id of referenced)assert.ok(ids.includes(id),"Missing DOM ID: "+id);
for(const id of ["impImages","impStream","impPoster","impBackdrop","impScan","impRealExample","impDraft","impPublish","impTest"]){
 assert.ok(ids.includes(id),"Importer control missing: "+id);
}
let handler=null;
const ctx={URL,Deno:{env:{get:()=>""},serve:fn=>{handler=fn;}},console,Response,TextDecoder,Uint8Array,AbortSignal,setTimeout,clearTimeout,fetch:()=>{throw Error("Network calls forbidden in parser unit test");}};
const functions=vm.runInNewContext(service+"\n;({parsePage,safeUrl})",ctx,{filename:"aseel-inspect-media/index.ts",timeout:1000});
assert.equal(typeof handler,"function");
assert.equal(typeof functions.parsePage,"function");
const base="https://example.org/movies/demo";
const fixture='<html><head><meta property="og:image" content="https://example.org/assets/poster.jpg"><meta name="description" content="Example description"><title>Sample Film 2024</title><script type="application/ld+json">{"@type":"VideoObject","duration":"PT1H12M","contentUrl":"https://example.org/media/film.mp4"}</script></head><body><img data-src="/assets/backdrop.jpg"><iframe src="https://archive.org/embed/demo"></iframe><video poster="/assets/scene.jpg"><source src="/media/film.m3u8" label="HD"></video></body></html>';
const result=functions.parsePage(fixture,base);
assert.equal(result.title_ar,"Sample Film 2024");
assert.equal(result.description,"Example description");
assert.equal(result.poster_url,"https://example.org/assets/poster.jpg");
assert.equal(result.backdrop_url,"https://example.org/assets/backdrop.jpg");
assert.equal(result.stream_url,"https://example.org/media/film.m3u8");
assert.equal(result.duration_minutes,72);
assert.ok(result.image_candidates.length>=3);
assert.ok(result.links.some(x=>x.url==="https://example.org/media/film.mp4"));
assert.ok(result.links.some(x=>x.kind==="embed"));
assert.ok(result.stream_variants.some(x=>x.label==="HD"));
const other=functions.parsePage('<video poster="/poster.png" src="/demo.mp4"></video>',base);
assert.equal(other.stream_url,"https://example.org/demo.mp4");
assert.equal(other.poster_url,"https://example.org/poster.png");
assert.equal(other.backdrop_url,other.poster_url);
assert.equal(functions.safeUrl("https://127.0.0.1/"),null);
assert.ok(functions.safeUrl("https://archive.org/details/test"));
console.log("PASS importer: DOM IDs, JS syntax, poster, backdrop, HLS, MP4, JSON-LD, nested iframe and URL safety");
