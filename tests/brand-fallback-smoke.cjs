"use strict";
const fs = require("fs");
const assert = require("assert");
const read = path => fs.readFileSync(path, "utf8");
const page = read("web/index.html");
const app = read("web/js/app.js");
const live = read("web/js/live.js");
const css = read("web/css/app.css");
const legacy = read("web/css/app-legacy.css");
const liveCss = read("web/css/live.css");

assert(fs.statSync("web/alizz-tv-transparent.png").size > 0, "Brand image must exist");
assert(!page.includes('src="assets/logo.svg"'), "All page branding must use the new logo");
assert(page.includes('<link rel="icon" href="alizz-tv-transparent.png"'));
assert(page.includes('brand__mark brand__mark--full'));
assert(page.includes('class="footer__logo"'));
assert(page.includes('class="gate__mark"'));
assert(app.includes('var DEFAULT_LOGO = "alizz-tv-transparent.png"'));
assert(app.includes('function heroFallback(item)'));
assert(app.includes("art(item) + (thumb ?"), "Search thumbnails must always keep a fallback under the cover");
assert(app.includes("'<div class=\"detail__poster\">' + art(item)"), "Detail posters must always keep the brand under covers");
assert(app.includes("var media = heroFallback(item)"), "Hero must keep a branded background");
assert(live.includes('class="live-channel-art__fallback"'));
assert(live.includes('class="live-channel-art__cover"'));
assert(live.includes('onerror="this.remove()"'), "Bad covers must reveal the brand");
assert(css.includes('.card__media .art__logo'));
assert(legacy.includes('.card__media .art__logo'));
assert(liveCss.includes('.live-poster .live-channel-art'));
console.log("PASS: full AL EZZ branding and missing/broken image fallbacks");
