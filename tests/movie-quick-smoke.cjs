"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),vm=require("node:vm");
const js=fs.readFileSync("admin/admin.js","utf8"),config=fs.readFileSync("admin/config.js","utf8");
const css=fs.readFileSync("admin/admin.css","utf8"),html=fs.readFileSync("admin/index.html","utf8");
new vm.Script(js,{filename:"admin/admin.js"});
new vm.Script(config,{filename:"admin/config.js"});
assert(js.includes("buildQuickMovieForm(tableCfg, form)"));
assert(js.includes("tableCfg.table === 'aseel_movies' && !row"));
assert(js.includes("id: 'movieQuickUrl'"));
assert(js.includes("movieQuickLinkType(link)"));
assert(js.includes("var extras = el('details'"));
assert(js.includes("field.closest('details')"));
assert(js.includes("errors.movie_quick_url"));
assert(js.includes("picker.querySelectorAll("));
assert(config.includes("movieCountries:"));
assert(css.includes(".drawer--quick-movie"));
assert(html.includes("admin.js?v=quick-movies-20261101"));
const match=js.match(/  function movieQuickLinkType\(value\) \{[\s\S]*?\n  \}/);
assert(match,"missing URL classifier");
const ctx={URL};vm.runInNewContext(match[0]+";result=movieQuickLinkType;",ctx);
const detect=ctx.result;
assert.equal(detect("https://example.com/video.mp4"),"stream");
assert.equal(detect("https://example.com/stream.m3u8?x=1"),"stream");
assert.equal(detect("https://www.youtube.com/watch?v=uCYv55twbhE"),"youtube");
assert.equal(detect("https://youtu.be/uCYv55twbhE"),"youtube");
for(const bad of ["http://example.com/film.mp4","https://example.com/page","https://youtube.com/","javascript:alert(1)"])assert.equal(detect(bad),"",bad);
console.log("PASS: streamlined movie creation and optional advanced controls");
